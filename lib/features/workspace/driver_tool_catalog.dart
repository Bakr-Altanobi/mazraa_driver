    this.id,
    this.ar,
    this.en,
    this.icon,
    this.endpoint, {
    this.group = 'account',
    this.form,
    this.pending = false,
  });
  final String id, ar, en, endpoint, group;
  final IconData icon;
  final String? form;
  final bool pending;
  String get route => '/tools/$id';
}

